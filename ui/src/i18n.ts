const DICTIONARIES: Record<Locale, Partial<Record<MessageKey, string>>> = { en, no }
const STORAGE_KEY = 'fjord.locale'

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string

export function translator(locale: Locale): Translate {
  return (key, vars) => {
    const template = DICTIONARIES[locale][key] ?? en[key] ?? key
    return vars ? template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`)) : template
  }
}

/** English unless the user picked something else earlier. */
export function initialLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved && saved in DICTIONARIES) return saved as Locale
  } catch {
    /* storage unavailable: fall back to English */
  }
  return 'en'
}

export function saveLocale(locale: Locale): void {
  try {
    localStorage.setItem(STORAGE_KEY, locale)
  } catch {
    /* non-fatal: the choice just won't persist */
  }
}

export function dateLocale(locale: Locale): string {
  return locale === 'no' ? 'nb-NO' : 'en-GB'
}
